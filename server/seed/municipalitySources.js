function buildMunicipalityCatalogSeed() {
  const publicationSourcesByKey = new Map(sharedSupplementalSources.map((source) => [source.sourceKey, source]));
  const municipalities = [];
  const municipalitySourceLinks = [];
  const municipalityQualityAssessments = [];

  for (const municipality of aargauMunicipalityNames) {
    const municipalityId = buildMunicipalityId(municipality);
    const rawPrefill = getRawMunicipalityPrefill(municipality);
    const operationalSource =
      aargauMunicipalitySources.find((source) => source.municipality === municipality) ??
      buildMunicipalitySourceDefaults(municipality);
    const officialWebsite = buildOfficialWebsite(rawPrefill, operationalSource);
    const primarySource = buildPrimarySourceDefinition(municipality, rawPrefill, operationalSource, officialWebsite);
    const primarySourceId = publicationSourcesByKey.get(primarySource.sourceKey)?.id ?? buildSourceId(primarySource.sourceKey);

    if (!publicationSourcesByKey.has(primarySource.sourceKey)) {
      publicationSourcesByKey.set(primarySource.sourceKey, {
        id: primarySourceId,
        ...primarySource
      });
    }

    municipalities.push({
      id: municipalityId,
      name: municipality,
      officialWebsite,
      createdAt: "2026-03-23T00:00:00.000Z",
      updatedAt: "2026-03-23T00:00:00.000Z"
    });

    municipalitySourceLinks.push({
      id: buildCatalogLinkId(municipalityId, primarySourceId, "primary"),
      municipalityId,
      sourceId: primarySourceId,
      relationType: "primary",
      directUrl: operationalSource.sourceUrl || officialWebsite,
      sourceType: operationalSource.sourceType,
      enabled: operationalSource.enabled ?? 0,
      digitalStatus: operationalSource.digitalStatus ?? "unknown",
      includePattern: operationalSource.includePattern ?? "",
      excludePattern: operationalSource.excludePattern ?? "",
      sourceToken: operationalSource.sourceToken ?? "",
      sharedHint: primarySource.isShared ? "Primärquelle wird mit anderen Gemeinden geteilt." : "",
      notes: operationalSource.notes ?? "",
      updatedAt: "2026-03-23T00:00:00.000Z"
    });

    municipalitySourceLinks.push({
      id: buildCatalogLinkId(municipalityId, "PUB-SHARED-AGIS-BAUGESUCHE", "supplemental"),
      municipalityId,
      sourceId: "PUB-SHARED-AGIS-BAUGESUCHE",
      relationType: "supplemental",
      directUrl: "https://www.ag.ch/geoportal/rest/services/AGIS/afb_bauges/MapServer",
      sourceType: "arcgis",
      enabled: 1,
      digitalStatus: "digital",
      includePattern: "",
      excludePattern: "",
      sourceToken: "",
      sharedHint: "Kantonale Zusatzquelle, mit allen Gemeinden geteilt.",
      notes: "Ergänzt die Gemeindequelle um Karten- und Datensatzprüfung.",
      updatedAt: "2026-03-23T00:00:00.000Z"
    });

    municipalitySourceLinks.push({
      id: buildCatalogLinkId(municipalityId, "PUB-SHARED-AMTSBLATT-AARGAU", "supplemental"),
      municipalityId,
      sourceId: "PUB-SHARED-AMTSBLATT-AARGAU",
      relationType: "supplemental",
      directUrl: "https://amtsblatt.ag.ch/publikationen/",
      sourceType: "html",
      enabled: 1,
      digitalStatus: "digital",
      includePattern: "baugesuch|baugesuche|baubewilligung|auflage",
      excludePattern: "",
      sourceToken: "",
      sharedHint: "Kantonale Zusatzquelle, mit allen Gemeinden geteilt.",
      notes: "Zusätzliche Publikations- und Monitoringquelle.",
      updatedAt: "2026-03-23T00:00:00.000Z"
    });

    const hasEbauAargauPortalAccess = eBauAargauMunicipalityNames.has(municipality);
    const mentionsEbauAargauPortal = /(?:ebauportal\.ag\.ch|baugesuch-online-einreichen)/i.test(
      `${rawPrefill.matchedSourceUrl} ${rawPrefill.matchedText}`
    );

    if (primarySource.sourceKey !== "shared:ebau-aargau" && (hasEbauAargauPortalAccess || mentionsEbauAargauPortal)) {
      municipalitySourceLinks.push({
        id: buildCatalogLinkId(municipalityId, "PUB-SHARED-EBAU-AARGAU", "supplemental"),
        municipalityId,
        sourceId: "PUB-SHARED-EBAU-AARGAU",
        relationType: "supplemental",
        directUrl: "https://ebauportal.ag.ch/",
        sourceType: "html",
        enabled: 0,
        digitalStatus: "digital",
        includePattern: "",
        excludePattern: "",
        sourceToken: "",
        sharedHint: "Digitale eBau-Gesuchseinreichung für diese Gemeinde möglich.",
        notes: hasEbauAargauPortalAccess
          ? buildEbauAargauPortalNote(municipality)
          : "Gemeinde verweist auf eBau Aargau, aber die Primärpublikation liegt an anderer Stelle.",
        updatedAt: "2026-03-23T00:00:00.000Z"
      });
    }

    const qualityAssessment = buildMunicipalityQualityAssessment(
      municipality,
      rawPrefill,
      operationalSource,
      publicationSourcesByKey.get(primarySource.sourceKey)
    );

    municipalityQualityAssessments.push({
      municipalityId,
      primarySourceId,
      rating: qualityAssessment.rating,
      rationale: qualityAssessment.rationale,
      sharedSourceNote: qualityAssessment.sharedSourceNote,
      uncertain: qualityAssessment.uncertain,
      updatedAt: "2026-03-23T00:00:00.000Z"
    });
  }

  return {
    municipalities,
    publicationSources: [...publicationSourcesByKey.values()],
    municipalitySourceLinks,
    municipalityQualityAssessments
  };
}

