function normalizeCatalogUrl(value) {
  if (!value) {
    return "";
  }

  try {
    const parsedUrl = new URL(String(value).trim());
    parsedUrl.hash = "";
    parsedUrl.search = "";
    const normalizedPath = parsedUrl.pathname.replace(/\/+$/, "");
    const pathname = normalizedPath || "/";
    return `${parsedUrl.protocol}//${parsedUrl.host.toLowerCase()}${pathname}`;
  } catch {
    return String(value).trim();
  }
}

function extractWebsiteRoot(value) {
  if (!value) {
    return "";
  }

  try {
    const parsedUrl = new URL(String(value).trim());
    return `${parsedUrl.protocol}//${parsedUrl.host.toLowerCase()}`;
  } catch {
    return "";
  }
}

